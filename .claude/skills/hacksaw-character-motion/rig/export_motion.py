# -*- coding: utf-8 -*-
"""
Emit the motion constants as JavaScript, from motion.py.

    python rig/export_motion.py

The gate measures the Python model; the game runs the JavaScript one. If those
two drift, the gate is checking something that is not shipping -- which is worse
than having no gate, because it reads as green. Keeping one hand-maintained copy
in each language is exactly how that drift happens.

So there is one source of truth, motion.py, and this writes the other. Run it
after any change to the tables and commit the output.
"""
from __future__ import print_function
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import motion

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, 'runtime', 'motion.generated.js')

HEAD = """// GENERATED by rig/export_motion.py from rig/motion.py -- do not edit.
// The gate measures the Python model and the game runs this one; they are
// generated from the same source so they cannot drift apart.
"""


def js_num(v):
    s = '%g' % v
    return s


def main():
    L = [HEAD]
    L.append('export const LOOP_MS = %d;' % motion.LOOP_MS)
    L.append('export const REACTION_MS = %d;' % motion.REACTION_MS)
    L.append('export const SNAP = %s, HOLD = %s;' % (js_num(motion.SNAP), js_num(motion.HOLD)))
    L.append('')
    L.append('// [ampDeg, lagMs, periodMs, oddScale]')
    L.append('export const IDLE = {')
    for k, v in motion.DEFAULTS.items():
        L.append('  %-8s [%s, %s, %s, %s],' % (k + ':', js_num(v[0]), js_num(v[1]),
                                               js_num(v[2]), js_num(v[3])))
    L.append('};')
    L.append('')
    L.append('// degrees at the peak of a reaction, added on top of the idle')
    L.append('export const REACTION = {')
    for k, v in motion.REACTION.items():
        L.append('  %-8s %s,' % (k + ':', js_num(v)))
    L.append('};')
    L.append('')
    L.append('// whole-figure shift at the peak, as a fraction of figure w/h.')
    L.append('// A root translation distorts nothing, so it has no ceiling.')
    L.append('export const REACTION_LIFT = [%s, %s];'
             % (js_num(motion.REACTION_LIFT[0]), js_num(motion.REACTION_LIFT[1])))
    p = motion.REACTION_PROP
    L.append('export const REACTION_PROP = {deg: %s, kickAt: %s, kickDeg: %s, stretch: %s};'
             % (js_num(p['deg']), js_num(p['kick_at']), js_num(p['kick_deg']),
                js_num(p['stretch'])))
    L.append('')
    L.append('// squash and stretch: [alongTheBone, acrossIt] at the peak.')
    L.append('// Rotating flat art carries no information about force -- every')
    L.append('// pixel keeps its place and the picture just tilts. Changing the')
    L.append('// shape is what reads as strain. Scaled by SCALE_K, which was')
    L.append('// swept against the fold and stretch gate.')
    L.append('export const REACTION_SCALE = {')
    for k, v in motion.REACTION_SCALE.items():
        L.append('  %-8s [%s, %s],' % (k + ':', js_num(v[0]), js_num(v[1])))
    L.append('};')
    L.append('export const SCALE_K = %s;' % js_num(motion.SCALE_K))
    f = motion.FLUTTER
    L.append('// the bulge shakes while it holds -- their biceps runs 1.40<->1.52')
    L.append('// on a 2-frame period. depth is a fraction OF THE BULGE, so a small')
    L.append('// one can never be pushed back through 1.0.')
    L.append('export const FLUTTER = {depth: %s, periodMs: %s};'
             % (js_num(f['depth']), js_num(f['period_ms'])))
    L.append('// bones whose scale passes down to their children (see motion.py)')
    L.append('export const SCALE_INHERIT = new Set([%s]);'
             % ', '.join('"%s"' % n for n in sorted(motion.SCALE_INHERIT)))
    L.append('')
    txt = '\n'.join(L)
    if not os.path.isdir(os.path.dirname(OUT)):
        os.makedirs(os.path.dirname(OUT))
    with open(OUT, 'w', encoding='utf-8') as f:
        f.write(txt)
    print('wrote %s  (%d idle, %d reaction, %d scale entries)'
          % (os.path.relpath(OUT, HERE), len(motion.DEFAULTS),
             len(motion.REACTION), len(motion.REACTION_SCALE)))


if __name__ == '__main__':
    import sys as _sys
    for _s in (_sys.stdout, _sys.stderr):  # Windows 的管線預設 cp950，agent 讀到會是亂碼
        if hasattr(_s, 'reconfigure'):
            _s.reconfigure(encoding='utf-8', errors='replace')
    main()
