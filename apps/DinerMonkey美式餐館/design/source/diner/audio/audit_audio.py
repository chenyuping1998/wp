"""Write the delivery level sheet using ffmpeg's EBU R128 meter."""
from pathlib import Path
import json
import math
import re
import subprocess
import wave

import imageio_ffmpeg
import numpy as np

HERE=Path(__file__).resolve().parent
OUT=HERE.parents[3]/'static/assets/audio/diner'
FF=imageio_ffmpeg.get_ffmpeg_exe()
rows=[]
for path in sorted(OUT.iterdir()):
    if path.suffix not in ('.wav','.mp3'):continue
    duration=0
    if path.suffix=='.wav':
        with wave.open(str(path),'rb') as w:duration=w.getnframes()/w.getframerate()
    else:
        duration=16*4*60/(132 if 'main' in path.name else 152)
    # EBU R128 uses 400 ms blocks. Pad very short cues to one block solely
    # for a comparable level reading; the delivered WAV is untouched.
    af=('apad=whole_dur=0.4,' if duration<.4 else '')+'loudnorm=I=-18:TP=-1:LRA=11:print_format=json'
    cmd=[FF,'-hide_banner','-nostats','-i',str(path),'-af',af,'-f','null','NUL']
    result=subprocess.run(cmd,capture_output=True,text=True,errors='replace')
    match=re.search(r'\{\s*"input_i"[\s\S]*?\}',result.stderr)
    meter=json.loads(match.group()) if match else {}
    lufs=meter.get('input_i','-inf')
    peak=meter.get('input_tp','?')
    rows.append((path.name,duration,peak,lufs,path.stat().st_size))
lines=['# Diner Monkey audio levels','','Measured with FFmpeg EBU R128 `loudnorm` input meter. Cues shorter than 400 ms are zero-padded to one measurement block for LUFS reporting only; the delivered WAVs retain their listed duration. All SFX are mono 44.1 kHz/16-bit WAV. Both runtime loops are stereo MP3 at 192 kbps; 48 kHz/24-bit WAV masters are in `masters/`.','',
       '| File | Duration (s) | True peak (dBTP) | Integrated LUFS | Bytes |','|---|---:|---:|---:|---:|']
for name,dur,peak,lufs,size in rows:lines.append(f'| {name} | {dur:.3f} | {peak} | {lufs} | {size:,} |')
lines+=['',f'Runtime audio total: {sum(x[4] for x in rows):,} bytes ({sum(x[4] for x in rows)/1048576:.2f} MiB).',
        'Generated by `build_audio.py` from original deterministic synthesis; no third-party recordings or recognizable song phrases.']
(HERE/'LEVELS.md').write_text('\n'.join(lines)+'\n',encoding='utf-8')
print(f'Wrote {HERE/"LEVELS.md"} ({len(rows)} files)')
