"""Paint background mesh weights from the existing art's leaf/linen colours.
No pixels are altered: these are sparse vertex influence fields on the far plate.
"""
from pathlib import Path
import json
import cv2,numpy as np
from PIL import Image
ROOT=Path(__file__).resolve().parent;APP=ROOT.parent
COLS,ROWS=128,72;W,H=1920,1080
SPECS={
 'feature':[
  ('upper_palm',(0,240,170,510),(0,430),'leaf',.9),
  ('lower_palm',(0,565,285,855),(30,810),'leaf',1.1),
  ('right_palm',(1605,480,1800,775),(1765,760),'leaf',.9)],
 'hold':[
  ('curtain_left',(0,0,335,400),(80,0),'cloth',1.2),
  ('curtain_right',(1560,0,1920,300),(1840,0),'cloth',1.2),
  ('drape_left',(0,760,365,1080),(90,790),'cloth',.8),
  ('drape_right',(1600,780,1890,1040),(1840,810),'cloth',.8)]}
result={}
for mode,specs in SPECS.items():
 name='bg_feature_far' if mode=='feature' else 'bg_holdandspin_far'
 rgb=np.array(Image.open(APP/'static/assets/sprites/mummyBackground'/f'{name}.webp').convert('RGB'));hsv=cv2.cvtColor(rgb,cv2.COLOR_RGB2HSV)
 fields=[]
 for name,rect,pivot,kind,amp in specs:
  x0,y0,x1,y1=rect;mask=np.zeros((H,W),np.float32)
  hue,sat,val=[hsv[:,:,i] for i in range(3)]
  select=((hue>=30)&(hue<=93)&(sat>90)&(val>65)) if kind=='leaf' else ((hue>=96)&(hue<=140)&(sat>95)&(val>35))
  mask[y0:y1,x0:x1]=select[y0:y1,x0:x1];mask=cv2.GaussianBlur(mask,(0,0),14)
  if mask.max():mask/=mask.max()
  weights=[]
  for r in range(ROWS+1):
   y=r*H/ROWS
   for c in range(COLS+1):
    x=c*W/COLS;edge=min(x-x0,x1-x,y-y0,y1-y);a=max(0,min(1,edge/36));a=a*a*(3-2*a)
    v=float(mask[min(H-1,round(y)),min(W-1,round(x))])*a
    if v>.002:weights.append([r*(COLS+1)+c,round(v,4)])
  fields.append(dict(name=name,rect=rect,pivot=pivot,kind=kind,amp=amp,weights=weights))
 result[mode]=fields
data=json.dumps(dict(cols=COLS,rows=ROWS,modes=result),separators=(',',':'))
out=APP/'src/game/tombSurfaceFields.ts';out.write_text('// Generated by design/build_tomb_fields.py; sparse vertex weights, no image pixels.\nexport default '+data+';\n')
print('Painted sparse foliage/cloth controls:',{k:sum(len(f['weights']) for f in v)for k,v in result.items()})
