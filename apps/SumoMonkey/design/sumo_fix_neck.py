"""HISTORICAL 10-24 PATCH REPAIR — superseded by the 10-25 re-split source.

Do not run this on the re-split cast: its neck is painted as a complete ImageGen
part, and its crops/matrices are regenerated by the official motion pipeline.

Replace the patch's three-blob neck with a solid fur column behind head and torso.

The 10-24 cast patch shipped neck.png as three small round caps, so whenever a glove
leaves the chin (idle, celebrate) the background shows between jaw and chest.
This paints a tapered fur column from inside the jaw down into the torso notch,
textured from the torso's own fur, re-crops the runtime texture and shifts the
baked neck matrices by the crop-origin change. Re-running is safe: the shift is
measured against the crop currently recorded in crops.json.
Usage: python3 design/sumo_fix_neck.py
"""
from pathlib import Path
import json
import numpy as np
from PIL import Image, ImageDraw, ImageFilter

R = Path(__file__).resolve().parents[1]
INK, INK_RGB = 4, np.array([12, 10, 9], np.float32)  # rim half-width px, outline colour
# Neck outline in source-canvas px. Front edge runs jaw -> chest notch; the back
# edge reaches out to the nape (under the ear, above the back shoulder), which
# the back glove hides in the drawing but idle/celebrate uncover.
SHAPE = {
    'mg': [(462, 300), (618, 300), (620, 510), (420, 510), (396, 440), (392, 380), (410, 338)],
    'fg': [(460, 370), (600, 370), (612, 580), (428, 580), (280, 500), (262, 455), (272, 410), (320, 378)],
}

for cast in ['mg', 'fg']:
    cdir = R / 'design/sumo_cast' / cast
    crops = json.loads((cdir / 'crops.json').read_text())
    torso = np.asarray(Image.open(cdir / 'layers/torso.png').convert('RGBA')).astype(np.float32)
    H, W = torso.shape[:2]

    # darkest fully opaque 96px fur patch in the torso
    lum = torso[:, :, :3].mean(2)
    best, P = None, 96
    for y in range(0, H - P, 16):
        for x in range(0, W - P, 16):
            if (torso[y:y + P, x:x + P, 3] < 250).any():
                continue
            m = lum[y:y + P, x:x + P].mean()
            if 25 < m < 90 and (best is None or m < best[0]):
                best = (m, x, y)
    _, px, py = best
    patch = torso[py:py + P, px:px + P, :3]
    tile = np.concatenate([patch, patch[:, ::-1]], 1)
    tile = np.concatenate([tile, tile[::-1]], 0)
    reps = (H // tile.shape[0] + 1, W // tile.shape[1] + 1, 1)
    fur = np.tile(tile, reps)[:H, :W] * 0.82

    poly = SHAPE[cast]
    big = Image.new('L', (W * 4, H * 4), 0)
    ImageDraw.Draw(big).polygon([(x * 4, y * 4) for x, y in poly], fill=255)
    big = big.filter(ImageFilter.GaussianBlur(40))  # round the corners
    big = big.point(lambda v: 255 if v > 128 else 0)
    # ink rim like the drawing's outline, in case an edge shows past hair/shoulder
    inner = big.filter(ImageFilter.MinFilter(4 * 2 * INK + 1))
    ink = np.asarray(big.resize((W, H), Image.LANCZOS)).astype(np.float32) - np.asarray(inner.resize((W, H), Image.LANCZOS)).astype(np.float32)
    mask = np.asarray(big.resize((W, H), Image.LANCZOS)).astype(np.float32)

    out = np.zeros((H, W, 4), np.float32)
    k = (ink.clip(0, 255) / 255)[:, :, None]
    out[:, :, :3] = fur * (1 - k) + INK_RGB * k
    out[:, :, 3] = mask
    out[mask < 2] = 0  # no stray colour outside the shape -> no fringe
    layer = Image.fromarray(out.round().clip(0, 255).astype(np.uint8))
    layer.save(cdir / 'layers/neck.png')

    ys, xs = np.nonzero(out[:, :, 3] > 0)
    nx0, ny0, nx1, ny1 = int(xs.min()) - 2, int(ys.min()) - 2, int(xs.max()) + 3, int(ys.max()) + 3
    layer.crop((nx0, ny0, nx1, ny1)).save(R / 'static/assets/sumoCast' / cast / 'neck.png')

    ox0, oy0 = crops['neck'][:2]
    dx, dy = nx0 - ox0, ny0 - oy0
    crops['neck'] = [nx0, ny0, nx1, ny1]
    (cdir / 'crops.json').write_text(json.dumps(crops))

    mpath = R / 'src/game' / f'sumoMotion_{cast}.json'
    motion = json.loads(mpath.read_text())
    i = motion['names'].index('neck')
    for clip in motion['clips'].values():
        for frame in clip['frames']:
            a, b, c, d, tx, ty = frame[i]
            frame[i] = [a, b, c, d, round(tx + a * dx + c * dy, 4), round(ty + b * dx + d * dy, 4)]
    mpath.write_text(json.dumps(motion, separators=(',', ':')))
    print(cast, 'fur patch', (px, py), 'neck crop', crops['neck'], 'shift', (dx, dy))
