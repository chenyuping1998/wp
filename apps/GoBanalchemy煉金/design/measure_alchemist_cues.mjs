import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
const app = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const store = path.resolve(app, '../../node_modules/.pnpm');
const core = fs.readdirSync(store).find((n) => n.startsWith('@esotericsoftware+spine-core@'));
const {
	TextureAtlas,
	AtlasAttachmentLoader,
	SkeletonJson,
	Skeleton,
	AnimationStateData,
	AnimationState,
	Physics,
} = await import(
	pathToFileURL(path.join(store, core, 'node_modules/@esotericsoftware/spine-core/dist/index.js'))
);
const dir = path.join(app, 'static/assets/spines/goBananasMonkey');
const atlas = new TextureAtlas(fs.readFileSync(path.join(dir, 'monkey.atlas'), 'utf8'));
const raw = JSON.parse(fs.readFileSync(path.join(dir, 'monkey.json'), 'utf8'));
const data = new SkeletonJson(new AtlasAttachmentLoader(atlas)).readSkeletonData(raw);
const skeleton = new Skeleton(data),
	state = new AnimationState(new AnimationStateData(data));
skeleton.setToSetupPose();
skeleton.updateWorldTransform(Physics.reset);
state.setAnimation(0, 'throwit', false);
state.setAnimation(1, 'flutter', true);
let elapsed = 0;
while (elapsed < 0.38) {
	const step = Math.min(1 / 120, 0.38 - elapsed);
	state.update(step);
	state.apply(skeleton);
	skeleton.update(step);
	skeleton.updateWorldTransform(Physics.update);
	elapsed += step;
}
let release;
if (raw.skeleton.hash === 'gb-alchemist-boom-v3') {
	const prop = skeleton.findBone('prop');
	if (!prop) throw new Error('Part-based alchemist has no prop grip bone');
	release = { x: prop.worldX, y: prop.worldY };
} else {
	const slot = skeleton.findSlot('alchemy_body'),
		mesh = slot.getAttachment(),
		xy = new Float32Array(mesh.worldVerticesLength);
	mesh.computeWorldVertices(slot, 0, xy.length, xy, 0, 2);
	const uvs = raw.skins[0].attachments.alchemy_body.alchemy_body.uvs;
	// Legacy full-body skin: measure the actual weighted palm instead of a bone.
	const point = [110 / 560, 546 / 884];
	for (let i = 0; i < mesh.triangles.length; i += 3) {
		const tri = mesh.triangles.slice(i, i + 3),
			[a, b, c] = tri.map((v) => [uvs[v * 2], uvs[v * 2 + 1]]);
		const den = (b[1] - c[1]) * (a[0] - c[0]) + (c[0] - b[0]) * (a[1] - c[1]);
		const wa = ((b[1] - c[1]) * (point[0] - c[0]) + (c[0] - b[0]) * (point[1] - c[1])) / den;
		const wb = ((c[1] - a[1]) * (point[0] - c[0]) + (a[0] - c[0]) * (point[1] - c[1])) / den,
			wc = 1 - wa - wb;
		if (Math.min(wa, wb, wc) < -1e-7) continue;
		const weights = [wa, wb, wc];
		release = {
			x: tri.reduce((sum, v, j) => sum + xy[v * 2] * weights[j], 0),
			y: tri.reduce((sum, v, j) => sum + xy[v * 2 + 1] * weights[j], 0),
		};
		break;
	}
}
if (!release) throw new Error('Grip point is outside the mascot mesh');
const cues = { releaseMs: 380, release: { x: +release.x.toFixed(3), y: +release.y.toFixed(3) } };
fs.writeFileSync(
	path.join(app, 'src/game/alchemistCues.ts'),
	'// Generated by design/measure_alchemist_cues.mjs.\nexport default ' +
		JSON.stringify(cues, null, 2) +
		' as const;\n',
);
console.log('Measured painted grip at release:', cues);
