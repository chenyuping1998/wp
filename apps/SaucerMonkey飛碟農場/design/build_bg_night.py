"""The light in the two night plates, cut out so it can live (2026-10-25, user:
「背景太靜態」 — same treatment as Putt Monkey's).

Additive crops of the plates' own brightest pixels, so a flicker can never be
the wrong shape or colour, plus the plate's stars found and listed:

  light_barn.png      the barn's lit windows                 (both plates)
  light_village.png   the village on the horizon             (both plates)
  ship_lights.png     the mothership's purple ports          (feature)
  ship_beam.png       the green tractor beam                 (feature)
  ship_circle.png     the crop circle under it               (feature)
  saucer_glow.png     the small saucer's lit rim             (base)
  soft_glow.png       a soft round halo (stars, fireflies, moon)

and src/game/bgNight.ts with every crop's box and the stars, in plate px.

    python design/build_bg_night.py
"""

import json
from pathlib import Path

import numpy as np
from PIL import Image, ImageFilter

APP = Path(__file__).resolve().parents[1]
PLATES = APP / "static/assets/sprites/sushiBackground"
OUT = APP / "static/assets/sprites/saucerNight"
TS = APP / "src/game/bgNight.ts"

BOXES = {
    # windows only: the corn tassels below them are the same yellow
    "light_barn": ("bg_base", (0, 290, 320, 456), "warm"),
    "light_village": ("bg_base", (1100, 375, 1850, 440), "warm"),
    "saucer_glow": ("bg_base", (400, 50, 530, 110), "gold"),
    "ship_lights": ("bg_feature", (540, 10, 1390, 220), "purple"),
    "ship_beam": ("bg_feature", (860, 180, 1075, 400), "green"),
    "ship_circle": ("bg_feature", (680, 425, 1260, 512), "purple"),
}
MOON = (1617, 155, 125)  # centre x, y, radius on the plate
# the sky stars are searched for in this box, outside the moon and the clouds
SKY = (0, 0, 1920, 330)
NOT_STARS = [(390, 30, 545, 125), (0, 250, 345, 330)]


def key(a, kind):
    R, G, B = a[..., 0], a[..., 1], a[..., 2]
    if kind == "warm":
        return np.clip((R - 190) / 50, 0, 1) * np.clip((G - 140) / 60, 0, 1) * np.clip((150 - B) / 60, 0, 1)
    if kind == "gold":
        return np.clip((R - 170) / 60, 0, 1) * np.clip((G - 120) / 60, 0, 1) * np.clip((R - B - 40) / 60, 0, 1)
    if kind == "purple":
        return np.clip((R - 150) / 60, 0, 1) * np.clip((B - 190) / 50, 0, 1) * np.clip((230 - G) / 60, 0, 1)
    if kind == "green":
        return np.clip((G - 140) / 60, 0, 1) * np.clip((G - R - 20) / 40, 0, 1)
    raise ValueError(kind)


def crop(name, plate, box, kind):
    a = np.asarray(Image.open(PLATES / f"{plate}.png").convert("RGB"), float)
    x0, y0, x1, y1 = box
    c = a[y0:y1, x0:x1]
    k = key(c, kind)
    h, w = k.shape
    yy, xx = np.mgrid[0:h, 0:w]
    edge = np.minimum.reduce([xx, w - 1 - xx, yy, h - 1 - yy]) / 10
    k *= np.clip(edge, 0, 1)
    g = Image.fromarray(np.clip(c * k[..., None], 0, 255).astype(np.uint8)).filter(ImageFilter.GaussianBlur(1.2))
    g.save(OUT / f"{name}.png", optimize=True)


def stars():
    a = np.asarray(Image.open(PLATES / "bg_base.png").convert("RGB"), float)
    lum = a.mean(-1)
    sat = a.max(-1) - a.min(-1)
    x0, y0, x1, y1 = SKY
    s = lum[y0:y1, x0:x1]
    bright = (s > 185) & (sat[y0:y1, x0:x1] < 80)
    # a star is a small bright spot on DARK sky: the clouds are bright too
    around = np.asarray(Image.fromarray(s.astype(np.uint8)).filter(ImageFilter.GaussianBlur(14)), float)
    cand = bright & (around < 95)
    ys, xs = np.nonzero(cand)
    pts = []
    for y, x in sorted(zip(ys, xs), key=lambda p: -s[p[0], p[1]]):
        X, Y = x + x0, y + y0
        if np.hypot(X - MOON[0], Y - MOON[1]) < MOON[2] + 40:
            continue
        # the saucer's rivets and the barn roof's highlights are not stars
        if any(b[0] <= X <= b[2] and b[1] <= Y <= b[3] for b in NOT_STARS):
            continue
        if all(np.hypot(X - p[0], Y - p[1]) > 18 for p in pts):
            # size: how far the bright spot reaches
            r = int((s[max(0, y - 8) : y + 9, max(0, x - 8) : x + 9] > 150).sum())
            pts.append((int(X), int(Y), r))
        if len(pts) >= 60:
            break
    return pts


def soft_glow(size=128):
    yy, xx = np.mgrid[0:size, 0:size]
    r = np.hypot(xx - (size - 1) / 2, yy - (size - 1) / 2) / (size / 2)
    f = np.clip(1 - r, 0, 1) ** 2.4
    v = (255 * f).astype(np.uint8)
    Image.fromarray(np.dstack([v, v, v])).save(OUT / "soft_glow.png", optimize=True)


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    for name, (plate, box, kind) in BOXES.items():
        crop(name, plate, box, kind)
    soft_glow()
    st = stars()
    ts = [
        "/** GENERATED by design/build_bg_night.py - do not edit by hand.",
        " *  The night plates' lights as additive crops, and their stars, in plate px. */",
        f"export const NIGHT_BOXES: Record<string, [number, number, number, number]> = {json.dumps({k: list(v[1]) for k, v in BOXES.items()})};",
        f"export const STARS: [number, number, number][] = {json.dumps(st)};",
        f"export const MOON: [number, number, number] = {json.dumps(list(MOON))};",
        "",
    ]
    TS.write_text("\n".join(ts), encoding="utf-8")
    print(f"{len(BOXES)} crops, {len(st)} stars")


if __name__ == "__main__":
    main()
