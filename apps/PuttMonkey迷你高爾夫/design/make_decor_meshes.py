"""Write src/game/meshWin/decorMeshes.ts for a Jade-family app: every separate
thing on the FG boards' and the big-win plaques' decor layers becomes a mesh
that answers the drop / slam and then sways (Diner's fgBoard.ts / winDecor.ts,
found automatically instead of hand-measured).

usage: make_decor_meshes.py <app dir> [--sheet out.png]
"""
import json, sys
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw
sys.path.insert(0,"E:/stake/tools/gen/python_libs")
from scipy import ndimage

app = Path(sys.argv[1])
V8 = app / 'static/assets/sprites/sushiV8'
LAYERS = {
    'v8FgIntroDecor': ('fg_intro_decor.png', 'board'),
    'v8FgTotalDecor': ('fg_total_decor.png', 'board'),
    'v8WinBig': ('win_big_decor.png', 'plaque'),
    'v8WinSuper': ('win_super_decor.png', 'plaque'),
    'v8WinMega': ('win_mega_decor.png', 'plaque'),
    'v8WinEpic': ('win_epic_decor.png', 'plaque'),
    'v8WinMax': ('win_max_decor.png', 'plaque'),
}
CANVAS = {'board': (1600, 1000), 'plaque': (1000, 560)}
MAX_THINGS = 6
PADPX = 34


def things(path, canvas):
    im = Image.open(path).convert('RGBA')
    sx, sy = canvas[0] / im.width, canvas[1] / im.height
    a = np.asarray(im)[..., 3] > 40
    lab, n = ndimage.label(ndimage.binary_dilation(a, iterations=6))
    out = []
    W, H = im.width, im.height
    for i in range(1, n + 1):
        m = (lab == i) & a
        area = int(m.sum())
        if area < 0.004 * W * H:
            continue
        ys, xs = np.nonzero(m)
        x0, y0, x1, y1 = xs.min(), ys.min(), xs.max() + 1, ys.max() + 1
        bw, bh = x1 - x0, y1 - y0
        # a thing spanning most of the layer is a frame ornament: it breathes, it does not swing
        frame = bw > 0.7 * W or bh > 0.8 * H
        # it hangs from / stands on the side nearest the board's middle
        cx, cy = W / 2, H / 2
        d = (xs - cx) ** 2 + (ys - cy) ** 2
        k = int(d.argmin())
        pivot = [round(float(xs[k]) * sx, 1), round(float(ys[k]) * sy, 1)]
        out.append({
            'rect': [round(float(v), 1) for v in (max(0, x0 - PADPX) * sx, max(0, y0 - PADPX) * sy, min(W, x1 + PADPX) * sx, min(H, y1 + PADPX) * sy)],
            'ink': [round(float(v), 1) for v in (x0 * sx, y0 * sy, x1 * sx, y1 * sy)],
            'pivot': pivot, 'area': float(area * sx * sy), 'frame': bool(frame),
        })
    out.sort(key=lambda t: -t['area'])
    return out[:MAX_THINGS]


data = {}
for key, (fname, kind) in LAYERS.items():
    p = V8 / fname
    if not p.exists():
        continue
    data[key] = {'kind': kind, 'things': things(p, CANVAS[kind])}

ts = '''/**
 * THE DECOR LAYERS ACT (2026-10-10): every separate thing on the free-spin
 * boards' decor (sushiV8/fg_*_decor.png) and on the big-win plaques' decor
 * (sushiV8/win_*_decor.png) is a mesh over its own rectangle of that layer.
 * It is thrown into a rock when the board drops or the plaque slams, then
 * sways about the side nearest the board's middle, each thing on its own beat.
 * A thing as wide as the layer (a frame ornament) only breathes.
 *
 * GENERATED by design/make_decor_meshes.py from the layers' alpha — re-run it
 * after the decor art changes. Rig units are layer pixels (board 1600 x 1000,
 * plaque 1000 x 560).
 */
import { flick, restPose, smoothstep, type MeshWinSpec, type Point, type Pose, type Rect, type Rig } from './meshRig';

export type DecorEnv = { /** ms since the board started to drop / the plaque to pop */ t: number };
export type DecorSpec = MeshWinSpec & { drive: (rig: Rig, env: DecorEnv) => Pose };
type Thing = { rect: Rect; ink: Rect; pivot: Point; area: number; frame: boolean };
type Layer = { kind: 'board' | 'plaque'; things: Thing[] };

const DATA: Record<string, Layer> = __DATA__;

const CANVAS = { board: [1600, 1000] as [number, number], plaque: [1000, 560] as [number, number] };
// the board lands at ~259ms of its drop (svelte backOut), the plaque at ~550ms
const LAND = { board: 259, plaque: 550 };
const wave = (t: number, period: number, phase = 0) => Math.sin((2 * Math.PI * t) / period + phase);
const inRect = (r: Rect, p: Point) => p[0] >= r[0] && p[0] <= r[2] && p[1] >= r[1] && p[1] <= r[3];

const build = (sprite: string, layer: Layer, th: Thing, i: number): DecorSpec => {
	const [cw, ch] = CANVAS[layer.kind];
	const r = th.rect;
	// a side on the canvas edge is not pinned: the art runs off it
	const depth = (p: Point) =>
		Math.max(0, Math.min(r[0] > 1 ? p[0] - r[0] : 1e9, r[2] < cw - 1 ? r[2] - p[0] : 1e9, r[1] > 1 ? p[1] - r[1] : 1e9, r[3] < ch - 1 ? r[3] - p[1] : 1e9));
	const size = Math.hypot(th.ink[2] - th.ink[0], th.ink[3] - th.ink[1]);
	// small things swing more, big ones less, so no rectangle edge is dragged far
	const deg = th.frame ? 0 : Math.max(0.6, Math.min(3, 320 / size));
	const step = Math.max(5, Math.round(size / 60));
	const spec: DecorSpec = {
		symbol: `decor:${sprite}:${i}`,
		key: sprite,
		sprite,
		mode: 'panel',
		feetY: r[3],
		durationMs: 3000,
		landMs: 99999,
		hitMs: 99999,
		inked: (p) => inRect(th.ink, p),
		rig: {
			canvas: CANVAS[layer.kind],
			grid: { x0: r[0], y0: r[1], x1: r[2], y1: r[3], cols: Math.max(4, Math.round((r[2] - r[0]) / step)), rows: Math.max(4, Math.round((r[3] - r[1]) / step)) },
			soft: 4,
			parts: [
				{ name: 'frame', pivot: [r[0], r[1]], dist: () => 10 },
				{
					name: 'thing',
					parent: 'frame',
					pivot: th.pivot,
					axis: [0, -1],
					priority: 1,
					dist: (p) => (inRect(th.ink, p) ? 0 : 8),
					keep: (p) => smoothstep((depth(p) - 3) / 26),
				},
			],
		},
		limits: { thing: { pos: deg, neg: deg } },
		drive: (rig, { t }) => {
			const pose = restPose(rig);
			const b = pose.bones[1];
			const land = LAND[layer.kind] + 60 * i;
			const s = i % 2 ? -1 : 1;
			const ramp = smoothstep((t - land) / 600);
			if (th.frame) {
				const k = 0.012 * flick(t, land, 3, 5) + 0.006 * wave(t, 2400, i) * ramp;
				b.along = 1 + k;
				b.across = 1 + k;
			} else {
				b.angle = s * deg * (0.75 * flick(t, land, 2.6, 3.2) + 0.3 * wave(t, 2200 + 300 * i, i) * ramp);
				b.dy = -0.006 * size * Math.max(0, flick(t, land, 4, 6));
			}
			return pose;
		},
		pose: (rig, t) => spec.drive(rig, { t }),
	};
	return spec;
};

const layerSpecs = (sprite: string): DecorSpec[] => (DATA[sprite]?.things ?? []).map((th, i) => build(sprite, DATA[sprite], th, i));

/** the decor meshes for the intro board or the total board */
export const FG_BOARD_DECOR = (settlement: boolean): DecorSpec[] => layerSpecs(settlement ? 'v8FgTotalDecor' : 'v8FgIntroDecor');
/** the decor meshes for each plaque, by its banner key */
export const WIN_DECOR: Record<string, DecorSpec[]> = Object.fromEntries(
	['v8WinBig', 'v8WinSuper', 'v8WinMega', 'v8WinEpic', 'v8WinMax'].map((k) => [k, layerSpecs(`${k}Decor`)]),
);
/** everything, for the gate */
export const DECOR_ALL: DecorSpec[] = [...FG_BOARD_DECOR(false), ...FG_BOARD_DECOR(true), ...Object.values(WIN_DECOR).flat()];
'''
# the plaques' decor sprites are `${bannerKey}Decor`
data2 = {}
for k, v in data.items():
    data2[k if k.endswith('Decor') else k + 'Decor'] = v
ts = ts.replace('__DATA__', json.dumps(data2, indent='\t').replace('true', 'true').replace('false', 'false'))
out = app / 'src/game/meshWin/decorMeshes.ts'
out.write_bytes(ts.encode('utf-8'))
print('wrote', out, {k: len(v['things']) for k, v in data2.items()})

if '--sheet' in sys.argv:
    sheet = sys.argv[sys.argv.index('--sheet') + 1]
    tiles = []
    for key, (fname, kind) in LAYERS.items():
        p = V8 / fname
        if not p.exists():
            continue
        cw, chh = CANVAS[kind]
        im = Image.open(p).convert('RGBA').resize((cw, chh))
        bg = Image.new('RGBA', im.size, (150, 165, 160, 255)); bg.alpha_composite(im)
        d = ImageDraw.Draw(bg)
        for th in data2[key if key.endswith('Decor') else key + 'Decor']['things']:
            d.rectangle(th['rect'], outline=(255, 0, 0) if not th['frame'] else (0, 0, 255), width=4)
            x, y = th['pivot']; d.ellipse([x - 10, y - 10, x + 10, y + 10], fill=(255, 230, 0))
        tiles.append(bg.resize((cw // 4, chh // 4)))
    W = 400 * 2; H = sum(t.height for t in tiles[::2]) + 10
    o = Image.new('RGB', (W, 1000), (40, 40, 40)); y = 0; x = 0
    for i, t in enumerate(tiles):
        o.paste(t, ((i % 2) * 400, (i // 2) * 250))
    o.save(sheet)
