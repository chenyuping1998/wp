"""constraint_selftest.py — 不需要官方 runtime、也不需要任何第三方素材的驗證。

    python constraint_selftest.py

`example/rigtest.json` 是自己編的合成骨架，把 IK（單節／雙節／compress／
stretch／uniform／softness／bendPositive 反轉）、transform 約束（world /
local × absolute / relative）、path 約束（proportional 間距、chainScale、
mixX≠mixY）以及 noRotationOrReflection / noScale 兩種繼承模式全部走過一遍。
素材是四個色塊，沒有任何別人的東西。

下面的黃金值是拿官方 spine-webgl 4.0.28 算出來的（`bonediff.py` 在那七個
時間點上都是 0.0000）。這支腳本把它們寫死，所以換一台機器不用裝
playwright、也不用抓官方 runtime，就能確認約束實作沒有跑掉。

判定：矩陣與座標都要落在 1e-5 以內。差到 0.01 以上就是真的算錯了。
"""
from __future__ import print_function

import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from spine import Skeleton                               # noqa: E402

TOL = 1e-5

# (時間, 骨, [a, b, c, d, worldX, worldY])
GOLDEN = None      # 由下方 _GOLDEN_TEXT 載入


def _load():
    rows = []
    for line in _GOLDEN_TEXT.strip().splitlines():
        parts = line.split()
        rows.append((float(parts[0]), parts[1],
                     [float(x) for x in parts[2:]]))
    return rows


def main():
    path = os.path.join(HERE, 'example', 'rigtest.json')
    if not os.path.exists(path):
        print('找不到 example/rigtest.json —— 這個包不完整')
        return 1
    sk = Skeleton(path, quiet=True)
    bad = 0
    checked = 0
    for t, bn, want in _load():
        sk.pose('move', t)
        M = sk.W[bn]
        got = [M[0, 0], M[0, 1], M[1, 0], M[1, 1], M[0, 2], M[1, 2]]
        d = max(abs(g - w) for g, w in zip(got, want))
        checked += 1
        if d > TOL:
            bad += 1
            print('  ✗ t=%-5s %-12s 差 %.6f' % (t, bn, d))
            print('      算出來 %s' % ['%.5f' % v for v in got])
            print('      應該是 %s' % ['%.5f' % v for v in want])
    print()
    if bad:
        print('%d / %d 項不符 —— 約束實作跟驗證當時不一致' % (bad, checked))
        return 1
    print('constraint selftest OK（%d 項，全部落在 %g 以內）' % (checked, TOL))
    print('IK、transform、path 三種約束與兩種繼承模式都跟官方 4.0 一致。')
    return 0


